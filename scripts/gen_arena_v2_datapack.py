"""Generate the sky-arena-v2 part of the data pack `mcrobot_demo` from mcrobot.arena_v2 (the single source of the layout).

Writes into datapack/mcrobot_demo/data/mcrobot_demo/function/: arena_v2.mcfunction (entry: /function mcrobot_demo:arena_v2), arena_v2/*.mcfunction
(place = generated fill commands, build, entities (labels + piston heads), setup, reset, remove, tick, second, cue/N, cue_back/N), run/cue
(macro: the mod's `cue` event), cam/5..8. The v1 arena (`arena`) is untouched; v2 stands 80 blocks north of it and reuses its timer functions
(run/start, run/finish, run/fall) and the scoreboard objective. The piston heads are display entities moved by commands from the cue events: there is
no redstone anywhere (owner rule). Version-specific syntax (block_display block_state: {Name, Properties} on 1.21.11, {id, properties} on 26.3, found on the real servers) lives in a
pack overlay for data format 121 (directory `overlay_26_3`), see pack.mcmeta written by gen_arena_datapack.py.

usage: PYTHONPATH=server python scripts/gen_arena_v2_datapack.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "server"))

from mcrobot import arena_v2 as A  # noqa: E402
from mcrobot.boxes import merge_boxes  # noqa: E402

PACK = ROOT / "datapack" / "mcrobot_demo"
FN = PACK / "data" / "mcrobot_demo" / "function"
OVERLAY = PACK / "overlay_26_3" / "data" / "mcrobot_demo" / "function"
OBJ = "mcr_arena"
TAG = "mcr_v2"
MAX_FILL = 32768
DIM = "execute in minecraft:overworld run"
EXTEND_TICKS = 3  # the head slides out in 3 ticks (0.15 s), stays 10 ticks, slides back in 3
HOLD_TICKS = 13


def write(rel: str, lines: list[str], base: Path = FN) -> None:
    p = base / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text("# generated by scripts/gen_arena_v2_datapack.py: do not edit\n" + "\n".join(lines) + "\n")


def place_lines(plan: A.PlanV2) -> list[str]:
    sx, sy, sz = plan.size
    states = sorted(set(plan.blocks.values()))
    labels = np.zeros((sx, sy, sz), np.int64)
    for (x, y, z), s in plan.blocks.items():
        labels[x, y, z] = states.index(s) + 1
    lines = []
    step = 32  # x slices of at most MAX_FILL blocks
    for xa in range(0, sx, step):
        xb = min(xa + step, sx) - 1
        assert (xb - xa + 1) * sy * sz <= MAX_FILL
        lines.append(f"fill ~{xa} ~0 ~0 ~{xb} ~{sy - 1} ~{sz - 1} minecraft:air")
    for x0, y0, z0, x1, y1, z1, lab in merge_boxes(labels):
        assert (x1 - x0) * (y1 - y0) * (z1 - z0) <= MAX_FILL
        lines.append(f"fill ~{x0} ~{y0} ~{z0} ~{x1 - 1} ~{y1 - 1} ~{z1 - 1} {states[lab - 1]}")
    return lines


def ab(x, y, z):  # region-local block -> world
    ox, oy, oz = A.ORIGIN
    return ox + x, oy + y, oz + z


def label_lines(plan: A.PlanV2) -> list[str]:
    out = []
    for lb in plan.labels:
        x, y, z = lb["x"] + A.ORIGIN[0], lb["y"] + A.ORIGIN[1], lb["z"] + A.ORIGIN[2]
        out.append(f"{DIM} summon minecraft:text_display {x:.2f} {y:.2f} {z:.2f} "
                   f"{{Tags:[\"{TAG}\",\"mcr_label\"],text:{{text:\"{lb['text']}\",color:\"{lb['color']}\",bold:1b}},billboard:\"center\",alignment:\"center\","
                   f"shadow:1b,see_through:0b,line_width:600,view_range:8.0f,transformation:{{translation:[0f,0f,0f],left_rotation:[0f,0f,0f,1f],scale:[5f,5f,5f],right_rotation:[0f,0f,0f,1f]}}}}")
        if lb["sub"]:
            out.append(f"{DIM} summon minecraft:text_display {x:.2f} {y - 1.6:.2f} {z:.2f} "
                       f"{{Tags:[\"{TAG}\",\"mcr_label\"],text:{{text:\"{lb['sub']}\",color:\"white\"}},billboard:\"center\",alignment:\"center\","
                       f"shadow:1b,see_through:0b,line_width:600,view_range:8.0f,transformation:{{translation:[0f,0f,0f],left_rotation:[0f,0f,0f,1f],scale:[2.6f,2.6f,2.6f],right_rotation:[0f,0f,0f,1f]}}}}")
    return out


def ram_state(facing: str, form: str) -> str:
    if form == "compound":  # 1.21.11: {Name, Properties}
        return f'{{Name:"minecraft:piston_head",Properties:{{facing:"{facing}",type:"normal",short:"false"}}}}'
    return f'{{id:"minecraft:piston_head",properties:{{facing:"{facing}",type:"normal",short:"false"}}}}'  # 26.3: id / properties, lowercase


def ram_lines(plan: A.PlanV2, form: str) -> list[str]:
    out = []
    for r in plan.rams:
        x, y, z = ab(*r["cell"])
        hx, hy, hz = r["hidden"]
        out.append(f"{DIM} summon minecraft:block_display {x} {y} {z} {{Tags:[\"{TAG}\",\"mcr_ram\",\"{r['tag']}\"],block_state:{ram_state(r['facing'], form)},"
                   f"transformation:{{translation:[{hx}f,{hy}f,{hz}f],left_rotation:[0f,0f,0f,1f],scale:[1f,1f,1f],right_rotation:[0f,0f,0f,1f]}}}}")
    return out


def ram_move(plan: A.PlanV2, push: int, extended: bool, ticks: int = EXTEND_TICKS) -> list[str]:
    """Slide the heads of one piston pair out (extended) or back in. All four heads of a push share one wall, so one hidden offset."""
    hid = {tuple(r["hidden"]) for r in plan.rams if r["push"] == push}
    assert len(hid) == 1
    hx, hy, hz = hid.pop()
    t = "0f,0f,0f" if extended else f"{hx}f,{hy}f,{hz}f"
    return [f"execute as @e[tag=mcr_ram_{push}] run data merge entity @s {{start_interpolation:0,interpolation_duration:{ticks},transformation:{{translation:[{t}]}}}}"]


def box_selector() -> str:
    ox, oy, oz = A.ORIGIN
    sx, sy, sz = A.SIZE
    return f"x={ox},y={oy - 8},z={oz},dx={sx},dy={sy + 40},dz={sz}"


def main() -> None:
    plan = A.build()
    ox, oy, oz = A.ORIGIN
    sx, sy, sz = plan.size
    fx0, fz0, fx1, fz1 = ox - 16, oz - 8, ox + sx + 24, oz + sz + 8
    box = box_selector()
    order = ["ramp", "beam", "slalom", "door", "ice", "lava", "push", "stairs"]
    gate_of = {g["key"]: g for g in plan.gates}
    next_gate = {k: gate_of[n] for k, n in zip(order, order[1:] + ["finish"])}

    write("arena_v2.mcfunction", [
        "tellraw @a {\"text\":\"[arena v2] loading chunks; the sky arena v2 is built in about 4 seconds\",\"color\":\"aqua\"}",
        f"{DIM} forceload add {fx0} {fz0} {fx1} {fz1}",
        "schedule function mcrobot_demo:arena_v2/build 60t replace",
    ])
    write("arena_v2/build.mcfunction", [
        f"execute in minecraft:overworld positioned {ox} {oy} {oz} run function mcrobot_demo:arena_v2/place",
        "function mcrobot_demo:arena_v2/rules",
        "function mcrobot_demo:arena_v2/entities",
        "function mcrobot_demo:arena_v2/setup",
        f"tellraw @a [{{\"text\":\"[arena v2] built at {ox} {oy} {oz} (course runs east). \",\"color\":\"aqua\"}},{{\"text\":\"/robot cam 5..8 for camera spots, /robot demo arena_v2 to start the G1.\",\"color\":\"white\"}}]",
    ])
    write("arena_v2/place.mcfunction", place_lines(plan))
    write("arena_v2/rules.mcfunction", [
        "# locks daytime and clear weather for the WHOLE world (gamerules are not per area); arena_v2/unlock reverts it",
        "gamerule advance_time false",
        "gamerule advance_weather false",
        f"{DIM} time set 6000",
        f"{DIM} weather clear 1000000",
    ])
    write("arena_v2/entities.mcfunction", [
        "# idempotent: removes the labels and piston heads of an earlier build, then summons them again",
        f"{DIM} kill @e[tag={TAG},{box}]",
        *label_lines(plan),
        "function mcrobot_demo:arena_v2/rams",
    ])
    write("arena_v2/rams.mcfunction", ram_lines(plan, "compound"))
    write("arena_v2/rams.mcfunction", ram_lines(plan, "string"), base=OVERLAY)
    write("arena_v2/setup.mcfunction", [
        f"scoreboard players set #v2 {OBJ} 1",
        f"scoreboard players set #cp {OBJ} 0",
        f"scoreboard players set #running {OBJ} 0",
        *[f"scoreboard players set #{n} {OBJ} {n}" for n in (2, 10, 20, 100)],
        *[f"scoreboard players add {h} {OBJ} 0" for h in ("Runs", "Falls", "Last_0.1s", "Best_0.1s")],
        f"scoreboard objectives setdisplay sidebar {OBJ}",
        f"bossbar set mcrobot_demo:timer players @a",
        "function mcrobot_demo:arena_v2/reset",
    ])
    # reset: strips and lamps off, rams hidden
    reset = [f"scoreboard players set #cp {OBJ} 0"]
    for st in plan.strips:
        x, y, z0 = ab(st["x"], A.FL, st["z0"])
        reset.append(f"{DIM} fill {x} {y} {z0} {x} {y} {oz + st['z1']} minecraft:{st['off']}")
    for g in plan.gates:
        for (lx, ly, lz) in g["lamps"]:
            reset.append(f"{DIM} setblock {ox + lx} {oy + ly} {oz + lz} minecraft:{g['lamp_off']}")
    for i in range(1, len(A.PUSH_STATIONS) + 1):
        reset += ram_move(plan, i, False, ticks=1)
    write("arena_v2/reset.mcfunction", reset)
    write("arena_v2/unlock.mcfunction", [
        "gamerule advance_time true",
        "gamerule advance_weather true",
        f"scoreboard players set #v2 {OBJ} 0",
        f"scoreboard players set #running {OBJ} 0",
        f"bossbar set mcrobot_demo:timer visible false",
        "scoreboard objectives setdisplay sidebar",
        "tellraw @a {\"text\":\"[arena v2] time and weather unlocked, mob clearing stopped (the blocks stay; arena_v2/remove deletes them)\",\"color\":\"aqua\"}",
    ])
    remove = ["function mcrobot_demo:arena_v2/unlock", f"{DIM} kill @e[tag={TAG},{box}]"]
    for xa in range(0, sx, 32):
        remove.append(f"execute in minecraft:overworld positioned {ox} {oy} {oz} run fill ~{xa} ~0 ~0 ~{min(xa + 32, sx) - 1} ~{sy - 1} ~{sz - 1} minecraft:air")
    remove.append(f"{DIM} forceload remove {fx0} {fz0} {fx1} {fz1}")
    write("arena_v2/remove.mcfunction", remove)
    write("arena_v2/tick.mcfunction", [f"execute if score #v2 {OBJ} matches 1 run function mcrobot_demo:arena_v2/tick_on"])
    write("arena_v2/tick_on.mcfunction", [
        f"scoreboard players add #t20v2 {OBJ} 1",
        f"execute if score #t20v2 {OBJ} matches 20.. run function mcrobot_demo:arena_v2/second",
        "# the run timer is driven by v1's tick when v1 is set up too (never twice)",
        f"execute if score #running {OBJ} matches 1 unless score #arena {OBJ} matches 1 run function mcrobot_demo:run/tick",
    ])
    write("arena_v2/second.mcfunction", [
        f"scoreboard players set #t20v2 {OBJ} 0",
        "# mob-free: anything that is not a player, a ghost part or an arena v2 label / piston head inside the arena box is removed once a second",
        f"execute in minecraft:overworld as @e[type=!minecraft:player,tag=!mcrobot_ghost,tag=!{TAG},{box}] run kill @s",
    ])
    # cues: 1..8 checkpoints, 11..13 pushes (sent by the demo through the mod's `cue` event)
    write("run/cue.mcfunction", ["# macro: {n:cue number}; sent by the demo through the mod", "$function mcrobot_demo:arena_v2/cue/$(n)"])
    for st in plan.strips:
        k = st["cue"]
        g = next_gate[st["key"]]
        x, y, z0 = ab(st["x"], A.FL, st["z0"])
        cx, cz = x + 0.5, oz + A.ZC
        lines = [
            f"scoreboard players set #cp {OBJ} {k}",
            f"{DIM} fill {x} {y} {z0} {x} {y} {oz + st['z1']} minecraft:{st['on']}",
        ]
        for (lx, ly, lz) in g["lamps"]:
            lines.append(f"{DIM} setblock {ox + lx} {oy + ly} {oz + lz} minecraft:{g['lamp_on']}")
        lines += [
            f"{DIM} particle minecraft:happy_villager {cx:.1f} {y + 1.5:.1f} {cz:.1f} 0.3 0.8 3.0 0 40 force",
            f"{DIM} particle minecraft:end_rod {cx:.1f} {y + 2.5:.1f} {cz:.1f} 0.2 1.0 3.0 0.03 30 force",
            f"{DIM} playsound minecraft:entity.experience_orb.pickup master @a {cx:.1f} {y + 2:.1f} {cz:.1f} 4 1.2",
            f"title @a actionbar {{\"text\":\"Checkpoint {k}/8: {A.SEC[st['key']].label} cleared\",\"color\":\"green\"}}",
        ]
        write(f"arena_v2/cue/{k}.mcfunction", lines)
    for i, pu in enumerate(plan.pushes, start=1):
        cx, cz = ox + pu["x"], oz + A.ZC
        write(f"arena_v2/cue/{pu['cue']}.mcfunction", [
            *ram_move(plan, i, True),
            f"{DIM} playsound minecraft:block.piston.extend block @a {cx:.1f} {oy + A.FL + 3} {cz:.1f} 3 1",
            f"schedule function mcrobot_demo:arena_v2/cue_back/{pu['cue']} {HOLD_TICKS}t replace",
        ])
        write(f"arena_v2/cue_back/{pu['cue']}.mcfunction", [
            *ram_move(plan, i, False),
            f"{DIM} playsound minecraft:block.piston.contract block @a {cx:.1f} {oy + A.FL + 3} {cz:.1f} 3 1",
        ])
    for k, (x, y, z, yaw, pitch) in A.cam_presets().items():
        write(f"cam/{k}.mcfunction", [
            "execute in minecraft:overworld run gamemode creative @s",
            f"execute in minecraft:overworld run tp @s {x:.1f} {y:.1f} {z:.1f} {yaw:.1f} {pitch:.1f}",
        ])
    n = len(place_lines(plan))
    print(f"arena v2 at {A.ORIGIN} size {plan.size}: {n} fill commands, {len(plan.labels)} labels, {len(plan.rams)} piston heads; functions written under {FN}")


if __name__ == "__main__":
    main()
