"""Generate the sky-arena part of the data pack `mcrobot_demo` from mcrobot.arena (the single source of the layout).

Writes into datapack/mcrobot_demo/data/mcrobot_demo/function/: arena.mcfunction (entry: /function mcrobot_demo:arena), arena/*.mcfunction
(place = generated fill commands, build, setup, rules, unlock, remove, tick, second), run/*.mcfunction (timer, progress, finish, fall: the demo
sends these through the mod), cam/1..4.mcfunction, load.mcfunction, and the load/tick function tags. Everything it changes in the world is
listed in README ("Sky arena"): the arena blocks, forceloaded chunks around it, the gamerules advance_time and advance_weather (global),
a scoreboard objective, a boss bar, and a once-a-second kill of non-player, non-ghost entities inside the arena box.

usage: PYTHONPATH=server python scripts/gen_arena_datapack.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "server"))

from mcrobot import arena  # noqa: E402
from mcrobot.boxes import merge_boxes  # noqa: E402

PACK = ROOT / "datapack" / "mcrobot_demo"
FN = PACK / "data" / "mcrobot_demo" / "function"
OBJ = "mcr_arena"
BAR = "mcrobot_demo:timer"
MAX_FILL = 32768


def write(rel: str, lines: list[str]) -> None:
    p = FN / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text("# generated by scripts/gen_arena_datapack.py: do not edit\n" + "\n".join(lines) + "\n")


def place_lines(plan: arena.Plan) -> list[str]:
    sx, sy, sz = plan.size
    states = sorted(set(plan.blocks.values()))
    labels = np.zeros((sx, sy, sz), np.int64)
    for (x, y, z), s in plan.blocks.items():
        labels[x, y, z] = states.index(s) + 1
    lines = []
    half = sx // 2  # two clears of at most MAX_FILL blocks
    for xa, xb in ((0, half - 1), (half, sx - 1)):
        assert (xb - xa + 1) * sy * sz <= MAX_FILL
        lines.append(f"fill ~{xa} ~0 ~0 ~{xb} ~{sy - 1} ~{sz - 1} minecraft:air")
    for x0, y0, z0, x1, y1, z1, lab in merge_boxes(labels):
        assert (x1 - x0) * (y1 - y0) * (z1 - z0) <= MAX_FILL
        lines.append(f"fill ~{x0} ~{y0} ~{z0} ~{x1 - 1} ~{y1 - 1} ~{z1 - 1} {states[lab - 1]}")
    return lines


def main() -> None:
    plan = arena.build_arena()
    ox, oy, oz = arena.ORIGIN
    sx, sy, sz = plan.size
    # chunks kept loaded: the arena plus the camera spots around it
    fx0, fz0, fx1, fz1 = ox - 16, oz - 8, ox + sx + 24, oz + sz + 8
    box = f"x={ox},y={oy - 8},z={oz},dx={sx},dy={sy + 40},dz={sz}"
    dim = "execute in minecraft:overworld run"

    write("arena.mcfunction", [
        "tellraw @a {\"text\":\"[arena] loading chunks; the sky arena is built in about 3 seconds\",\"color\":\"aqua\"}",
        f"{dim} forceload add {fx0} {fz0} {fx1} {fz1}",
        "schedule function mcrobot_demo:arena/build 60t replace",
    ])
    write("arena/build.mcfunction", [
        f"execute in minecraft:overworld positioned {ox} {oy} {oz} run function mcrobot_demo:arena/place",
        "function mcrobot_demo:arena/rules",
        "function mcrobot_demo:arena/setup",
        f"tellraw @a [{{\"text\":\"[arena] sky arena built at {ox} {oy} {oz} (course runs east). \",\"color\":\"aqua\"}},{{\"text\":\"/robot cam 1..4 for camera spots, /robot demo arena to start the G1.\",\"color\":\"white\"}}]",
    ])
    write("arena/place.mcfunction", place_lines(plan))
    write("arena/rules.mcfunction", [
        "# locks daytime and clear weather for the WHOLE world (gamerules are not per area); arena/unlock reverts it",
        "gamerule advance_time false",
        "gamerule advance_weather false",
        f"{dim} time set 6000",
        f"{dim} weather clear 1000000",
    ])
    write("arena/setup.mcfunction", [
        f"scoreboard players set #arena {OBJ} 1",
        f"scoreboard players set #20 {OBJ} 20",
        f"scoreboard players set #running {OBJ} 0",
        f"scoreboard players add Runs {OBJ} 0",
        f"scoreboard players add Falls {OBJ} 0",
        f"scoreboard players add Last_0.1s {OBJ} 0",
        f"scoreboard players add Best_0.1s {OBJ} 0",
        f"scoreboard objectives setdisplay sidebar {OBJ}",
        f"bossbar set {BAR} players @a",
    ])
    write("arena/unlock.mcfunction", [
        "gamerule advance_time true",
        "gamerule advance_weather true",
        f"scoreboard players set #arena {OBJ} 0",
        f"scoreboard players set #running {OBJ} 0",
        f"bossbar set {BAR} visible false",
        "scoreboard objectives setdisplay sidebar",
        "tellraw @a {\"text\":\"[arena] time and weather unlocked, mob clearing stopped (the arena blocks stay; arena/remove deletes them)\",\"color\":\"aqua\"}",
    ])
    write("arena/remove.mcfunction", [
        "function mcrobot_demo:arena/unlock",
        f"execute in minecraft:overworld positioned {ox} {oy} {oz} run fill ~0 ~0 ~0 ~{sx // 2 - 1} ~{sy - 1} ~{sz - 1} minecraft:air",
        f"execute in minecraft:overworld positioned {ox} {oy} {oz} run fill ~{sx // 2} ~0 ~0 ~{sx - 1} ~{sy - 1} ~{sz - 1} minecraft:air",
        f"{dim} forceload remove {fx0} {fz0} {fx1} {fz1}",
    ])
    write("arena/tick.mcfunction", [f"execute if score #arena {OBJ} matches 1 run function mcrobot_demo:arena/tick_on"])
    write("arena/tick_on.mcfunction", [
        f"scoreboard players add #t20 {OBJ} 1",
        f"execute if score #t20 {OBJ} matches 20.. run function mcrobot_demo:arena/second",
        f"execute if score #running {OBJ} matches 1 run function mcrobot_demo:run/tick",
    ])
    write("arena/second.mcfunction", [
        f"scoreboard players set #t20 {OBJ} 0",
        "# mob-free: anything that is not a player or a ghost display part inside the arena box is removed once a second",
        f"execute in minecraft:overworld as @e[type=!minecraft:player,tag=!mcrobot_ghost,{box}] run kill @s",
    ])
    write("load.mcfunction", [
        f"scoreboard objectives add {OBJ} dummy {{\"text\":\"G1 sky arena\"}}",
        f"bossbar add {BAR} {{\"text\":\"G1 run\"}}",
        f"bossbar set {BAR} max 100",
    ])
    # --- run timer, driven by the demo through the mod (start / progress / finish / fall)
    name = ("[{\"text\":\"G1 run  \",\"color\":\"white\"},{\"score\":{\"name\":\"#sec\",\"objective\":\"" + OBJ + "\"}},{\"text\":\".\"},"
            "{\"score\":{\"name\":\"#tenth\",\"objective\":\"" + OBJ + "\"}},{\"text\":\" s\"}]")
    write("run/start.mcfunction", [
        f"scoreboard players set #ticks {OBJ} 0",
        f"scoreboard players set #running {OBJ} 1",
        f"scoreboard players set #progress {OBJ} 0",
        f"bossbar set {BAR} color white",
        f"bossbar set {BAR} players @a",
        f"bossbar set {BAR} visible true",
        f"execute store result bossbar {BAR} value run scoreboard players get #progress {OBJ}",
        f"execute if score #v2 {OBJ} matches 1 run function mcrobot_demo:arena_v2/reset",  # arena v2 (gen_arena_v2_datapack.py): checkpoints off, pistons in
    ])
    write("run/tick.mcfunction", [
        f"scoreboard players add #ticks {OBJ} 1",
        f"scoreboard players operation #sec {OBJ} = #ticks {OBJ}",
        f"scoreboard players operation #sec {OBJ} /= #20 {OBJ}",
        f"scoreboard players operation #tenth {OBJ} = #ticks {OBJ}",
        f"scoreboard players operation #tenth {OBJ} %= #20 {OBJ}",
        f"scoreboard players operation #tenth {OBJ} /= #2 {OBJ}",
        f"scoreboard players operation #par {OBJ} = #ticks {OBJ}",
        f"scoreboard players operation #par {OBJ} %= #2 {OBJ}",
        f"execute if score #par {OBJ} matches 0 run bossbar set {BAR} name {name}",  # the text changes every 2nd tick only
    ])
    write("run/progress.mcfunction", [
        "# macro: {pct:0..100}",
        f"$execute store result bossbar {BAR} value run scoreboard players set #progress {OBJ} $(pct)",
    ])
    final = ("[{\"text\":\"FINISHED  \",\"color\":\"green\"},{\"score\":{\"name\":\"#sec\",\"objective\":\"" + OBJ + "\"}},{\"text\":\".\"},"
             "{\"score\":{\"name\":\"#tenth\",\"objective\":\"" + OBJ + "\"}},{\"text\":\" s\"}]")
    write("run/finish.mcfunction", [
        "# macro: {cs:centiseconds of simulated time}",
        f"scoreboard players set #running {OBJ} 0",
        f"$scoreboard players set #cs {OBJ} $(cs)",
        f"scoreboard players operation #sec {OBJ} = #cs {OBJ}",
        f"scoreboard players operation #sec {OBJ} /= #100 {OBJ}",
        f"scoreboard players operation #tenth {OBJ} = #cs {OBJ}",
        f"scoreboard players operation #tenth {OBJ} %= #100 {OBJ}",
        f"scoreboard players operation #tenth {OBJ} /= #10 {OBJ}",
        f"scoreboard players operation Last_0.1s {OBJ} = #cs {OBJ}",
        f"scoreboard players operation Last_0.1s {OBJ} /= #10 {OBJ}",
        f"execute if score Best_0.1s {OBJ} matches 0 run scoreboard players operation Best_0.1s {OBJ} = Last_0.1s {OBJ}",
        f"execute if score Last_0.1s {OBJ} < Best_0.1s {OBJ} run scoreboard players operation Best_0.1s {OBJ} = Last_0.1s {OBJ}",
        f"scoreboard players add Runs {OBJ} 1",
        f"bossbar set {BAR} color green",
        f"bossbar set {BAR} name {final}",
        f"execute store result bossbar {BAR} value run scoreboard players set #progress {OBJ} 100",
    ])
    write("run/fall.mcfunction", [
        f"scoreboard players set #running {OBJ} 0",
        f"scoreboard players add Falls {OBJ} 1",
        f"bossbar set {BAR} color red",
        f"bossbar set {BAR} name {{\"text\":\"The G1 fell: resetting\",\"color\":\"red\"}}",
    ])
    # constants the timer divides by
    setup = FN / "arena" / "setup.mcfunction"
    setup.write_text(setup.read_text() + "\n".join(f"scoreboard players set #{n} {OBJ} {n}" for n in (2, 10, 100)) + "\n")
    # camera spots
    for k, (x, y, z, yaw, pitch) in arena.cam_presets().items():
        write(f"cam/{k}.mcfunction", [
            f"execute in minecraft:overworld run gamemode creative @s",
            f"execute in minecraft:overworld run tp @s {x:.1f} {y:.1f} {z:.1f} {yaw:.1f} {pitch:.1f}",
        ])
    # tags
    tags = PACK / "data" / "minecraft" / "tags" / "function"
    tags.mkdir(parents=True, exist_ok=True)
    (tags / "load.json").write_text(json.dumps({"values": ["mcrobot_demo:load"]}, indent=2) + "\n")
    (tags / "tick.json").write_text(json.dumps({"values": ["mcrobot_demo:arena/tick", "mcrobot_demo:arena_v2/tick"]}, indent=2) + "\n")
    # overlay_26_3 (data format 121 = 26.3): arena v2's piston heads use block_display's string block_state there (gen_arena_v2_datapack.py)
    (PACK / "pack.mcmeta").write_text(json.dumps({
        "pack": {"description": "minecraft-robot-sim demo maze and sky arenas", "min_format": 94, "max_format": 121},
        "overlays": {"entries": [{"min_format": 121, "max_format": 121, "directory": "overlay_26_3"}]},
    }, indent=2) + "\n")
    n = len(place_lines(plan))
    print(f"arena at {arena.ORIGIN} size {plan.size}: {n} fill commands; functions written under {FN}")


if __name__ == "__main__":
    main()
